//! TypeScript from `schema/v8.json` (RFC 0003 §9).
//!
//! Emits, into `packages/waku-client/src/v8/generated/`:
//! - `types.ts`: every `$defs` type. Tagged unions are discriminated unions
//!   whose fallback is `{ type: "unknown"; rawType: string }`; open string
//!   enums are their known literals plus `(string & {})`; optional fields
//!   are `field?: T`.
//! - `methods.ts` / `streams.ts`: typed maps from method and stream names to
//!   their params, results, specs and items, with the scope tables.
//! - `decode.ts`: normalizers that walk only the parts of a decoded value
//!   that contain open unions and replace unknown tags with the fallback, so
//!   an exhaustive `switch` stays sound against a newer daemon.
//! - `constants.ts` and `index.ts`.
//!
//! Output is a pure function of the schema, so regeneration is byte-stable.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use serde_json::{Map, Value};

const HEADER: &str =
    "// Generated by waku-codegen from crates/waku-protocol/schema/v8.json. Do not edit.\n";

/// File name → contents.
pub fn generate(document: &Value) -> BTreeMap<String, String> {
    let document = &crate::canonical(document);
    let definitions = document
        .get("$defs")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();
    let generator = Generator {
        needs: normalization_table(&definitions),
        definitions,
    };
    let mut files = BTreeMap::new();
    files.insert("types.ts".to_owned(), generator.types());
    files.insert("methods.ts".to_owned(), generator.methods(document));
    files.insert("streams.ts".to_owned(), generator.streams(document));
    files.insert("decode.ts".to_owned(), generator.decode(document));
    files.insert("constants.ts".to_owned(), constants(document));
    files.insert(
        "index.ts".to_owned(),
        format!(
            "{HEADER}export type * from \"./types\";\n\
             export * from \"./constants\";\n\
             export * from \"./decode\";\n\
             export * from \"./methods\";\n\
             export * from \"./streams\";\n"
        ),
    );
    files
}

struct Generator {
    definitions: Map<String, Value>,
    /// Definitions whose decoded values contain an open union somewhere.
    needs: BTreeSet<String>,
}

fn reference_name(schema: &Value) -> Option<&str> {
    schema
        .get("$ref")
        .and_then(Value::as_str)
        .and_then(|reference| reference.strip_prefix("#/$defs/"))
}

fn is_null(schema: &Value) -> bool {
    schema.get("type").and_then(Value::as_str) == Some("null")
}

fn tag_of(variant: &Value) -> Option<&str> {
    variant
        .pointer("/properties/type/const")
        .and_then(Value::as_str)
}

fn is_unknown_tag(tag: &str) -> bool {
    tag.eq_ignore_ascii_case("unknown")
}

/// `schema` without its `null` alternative (an `Option`).
fn without_null(schema: &Value) -> Value {
    if let Some(any_of) = schema.get("anyOf").and_then(Value::as_array) {
        let rest = any_of
            .iter()
            .filter(|alternative| !is_null(alternative))
            .collect::<Vec<_>>();
        if rest.len() == 1 {
            return rest[0].clone();
        }
    }
    if let Some(types) = schema.get("type").and_then(Value::as_array) {
        let rest = types
            .iter()
            .filter(|kind| kind.as_str() != Some("null"))
            .cloned()
            .collect::<Vec<_>>();
        let mut stripped = schema.clone();
        stripped["type"] = if rest.len() == 1 {
            rest[0].clone()
        } else {
            Value::Array(rest)
        };
        return stripped;
    }
    schema.clone()
}

fn property_name(name: &str) -> String {
    let mut characters = name.chars();
    let valid = characters
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic() || first == '_' || first == '$')
        && characters.all(|rest| rest.is_ascii_alphanumeric() || rest == '_' || rest == '$');
    if valid {
        name.to_owned()
    } else {
        serde_json::to_string(name).expect("a string serializes")
    }
}

fn doc_comment(schema: &Value, indent: &str) -> String {
    let Some(description) = schema.get("description").and_then(Value::as_str) else {
        return String::new();
    };
    let description = description.replace("*/", "*\\/");
    let lines = description.lines().collect::<Vec<_>>();
    if lines.len() == 1 {
        return format!("{indent}/** {} */\n", lines[0].trim_end());
    }
    let mut comment = format!("{indent}/**\n");
    for line in lines {
        let line = line.trim_end();
        if line.is_empty() {
            let _ = writeln!(comment, "{indent} *");
        } else {
            let _ = writeln!(comment, "{indent} * {line}");
        }
    }
    let _ = writeln!(comment, "{indent} */");
    comment
}

/// Which definitions contain an open union, to a fixed point.
fn normalization_table(definitions: &Map<String, Value>) -> BTreeSet<String> {
    let mut needs = BTreeSet::new();
    loop {
        let before = needs.len();
        for (name, schema) in definitions {
            if !needs.contains(name) && schema_needs(schema, &needs) {
                needs.insert(name.clone());
            }
        }
        if needs.len() == before {
            return needs;
        }
    }
}

fn schema_needs(schema: &Value, needs: &BTreeSet<String>) -> bool {
    if let Some(name) = reference_name(schema)
        && needs.contains(name)
    {
        return true;
    }
    if let Some(variants) = schema.get("oneOf").and_then(Value::as_array) {
        if variants
            .iter()
            .any(|variant| tag_of(variant).is_some_and(is_unknown_tag))
        {
            return true;
        }
        if variants.iter().any(|variant| schema_needs(variant, needs)) {
            return true;
        }
    }
    if let Some(alternatives) = schema.get("anyOf").and_then(Value::as_array)
        && alternatives
            .iter()
            .any(|alternative| schema_needs(alternative, needs))
    {
        return true;
    }
    if let Some(properties) = schema.get("properties").and_then(Value::as_object)
        && properties
            .values()
            .any(|property| schema_needs(property, needs))
    {
        return true;
    }
    for key in ["items", "additionalProperties"] {
        if let Some(inner) = schema.get(key)
            && inner.is_object()
            && schema_needs(inner, needs)
        {
            return true;
        }
    }
    false
}

impl Generator {
    /// The TypeScript type of `schema`. `prefix` qualifies references
    /// (`"T."` outside `types.ts`).
    fn ts_type(&self, schema: &Value, prefix: &str, indent: usize) -> String {
        let Some(object) = schema.as_object() else {
            return "unknown".into();
        };
        if object.contains_key("x-waku-dependent") {
            return "unknown".into();
        }
        if let Some(variants) = object.get("oneOf").and_then(Value::as_array) {
            return variants
                .iter()
                .map(|variant| self.variant_type(variant, prefix, indent))
                .collect::<Vec<_>>()
                .join(" | ");
        }
        if let Some(name) = reference_name(schema) {
            return format!("{prefix}{name}");
        }
        if let Some(alternatives) = object.get("anyOf").and_then(Value::as_array) {
            return alternatives
                .iter()
                .map(|alternative| self.ts_type(alternative, prefix, indent))
                .collect::<Vec<_>>()
                .join(" | ");
        }
        if let Some(constant) = object.get("const") {
            return constant.to_string();
        }
        if let Some(values) = object.get("enum").and_then(Value::as_array) {
            let mut literals = values.iter().map(Value::to_string).collect::<Vec<_>>();
            if object.get("x-waku-open") == Some(&Value::Bool(true)) {
                literals.push("(string & {})".into());
            }
            return literals.join(" | ");
        }
        match object.get("type") {
            Some(Value::Array(kinds)) => kinds
                .iter()
                .map(|kind| {
                    let mut single = schema.clone();
                    single["type"] = kind.clone();
                    self.ts_type(&single, prefix, indent)
                })
                .collect::<Vec<_>>()
                .join(" | "),
            Some(Value::String(kind)) => match kind.as_str() {
                "string" => "string".into(),
                "integer" | "number" => "number".into(),
                "boolean" => "boolean".into(),
                "null" => "null".into(),
                "array" => format!(
                    "Array<{}>",
                    object
                        .get("items")
                        .map(|items| self.ts_type(items, prefix, indent))
                        .unwrap_or_else(|| "unknown".into())
                ),
                "object" => self.object_type(schema, prefix, indent, None),
                _ => "unknown".into(),
            },
            _ => "unknown".into(),
        }
    }

    fn object_type(
        &self,
        schema: &Value,
        prefix: &str,
        indent: usize,
        tag: Option<&str>,
    ) -> String {
        let properties = schema.get("properties").and_then(Value::as_object);
        if properties.is_none_or(Map::is_empty) {
            return match schema.get("additionalProperties") {
                Some(values @ Value::Object(_)) => {
                    format!(
                        "{{ [key: string]: {} }}",
                        self.ts_type(values, prefix, indent)
                    )
                }
                _ => "Record<string, never>".into(),
            };
        }
        let properties = properties.expect("checked above");
        let required = schema
            .get("required")
            .and_then(Value::as_array)
            .map(|names| {
                names
                    .iter()
                    .filter_map(Value::as_str)
                    .collect::<BTreeSet<_>>()
            })
            .unwrap_or_default();
        let inner = "  ".repeat(indent + 1);
        let mut text = String::from("{\n");
        let mut names = properties.keys().map(String::as_str).collect::<Vec<_>>();
        // The tag first, then the fields in schema order.
        names.sort_by_key(|name| *name != "type");
        for name in names {
            let property = &properties[name];
            text.push_str(&doc_comment(property, &inner));
            if name == "type"
                && let Some(tag) = tag
            {
                let _ = writeln!(
                    text,
                    "{inner}type: {};",
                    serde_json::to_string(tag).unwrap()
                );
                continue;
            }
            let optional = !required.contains(name);
            let property = if optional {
                without_null(property)
            } else {
                property.clone()
            };
            let _ = writeln!(
                text,
                "{inner}{}{}: {};",
                property_name(name),
                if optional { "?" } else { "" },
                self.ts_type(&property, prefix, indent + 1)
            );
        }
        let _ = write!(text, "{}}}", "  ".repeat(indent));
        text
    }

    fn variant_type(&self, variant: &Value, prefix: &str, indent: usize) -> String {
        let tag = tag_of(variant);
        if tag.is_some_and(is_unknown_tag) {
            return "{ type: \"unknown\"; rawType: string }".into();
        }
        let own = self.object_type(variant, prefix, indent, tag);
        match reference_name(variant) {
            Some(name) => format!("({own} & {prefix}{name})"),
            None => own,
        }
    }

    fn types(&self) -> String {
        let mut text = String::from(HEADER);
        for (name, schema) in &self.definitions {
            text.push('\n');
            text.push_str(&doc_comment(schema, ""));
            let _ = writeln!(
                text,
                "export type {name} = {};",
                self.ts_type(schema, "", 0)
            );
        }
        text
    }

    fn methods(&self, document: &Value) -> String {
        let methods = document
            .get("methods")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        let mut text = format!("{HEADER}\nimport type * as T from \"./types\";\n\n");
        text.push_str("/** Every method: its params and its result (`reply.ok`). */\n");
        text.push_str("export interface Methods {\n");
        for method in &methods {
            let name = method["name"].as_str().unwrap_or_default();
            let _ = writeln!(
                text,
                "  {}: {{\n    params: {};\n    result: {};\n  }};",
                serde_json::to_string(name).unwrap(),
                self.ts_type(&method["params"], "T.", 2),
                self.ts_type(&method["result"], "T.", 2)
            );
        }
        text.push_str("}\n\n");
        text.push_str(
            "export type MethodName = keyof Methods;\n\
             export type MethodParams<M extends MethodName> = Methods[M][\"params\"];\n\
             export type MethodResultOf<M extends MethodName> = Methods[M][\"result\"];\n\n\
             export interface MethodInfo {\n\
             \x20 /** The scope a credential needs, before payload-dependent additions. */\n\
             \x20 readonly scope: T.Scope;\n\
             \x20 /** Whether the method mutates and carries an `opId`. */\n\
             \x20 readonly opId: boolean;\n\
             }\n\n\
             export const METHODS: { readonly [M in MethodName]: MethodInfo } = {\n",
        );
        for method in &methods {
            let _ = writeln!(
                text,
                "  {}: {{ scope: {}, opId: {} }},",
                serde_json::to_string(method["name"].as_str().unwrap_or_default()).unwrap(),
                method["scope"],
                method["opId"]
            );
        }
        text.push_str("};\n");
        text
    }

    fn streams(&self, document: &Value) -> String {
        let streams = document
            .get("streams")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        let mut text = format!("{HEADER}\nimport type * as T from \"./types\";\n\n");
        text.push_str("/** Every stream: its subscription spec and its items. */\n");
        text.push_str("export interface Streams {\n");
        for stream in &streams {
            let _ = writeln!(
                text,
                "  {}: {{\n    spec: {};\n    item: {};\n  }};",
                property_name(stream["name"].as_str().unwrap_or_default()),
                self.ts_type(&stream["spec"], "T.", 2),
                self.ts_type(&stream["item"], "T.", 2)
            );
        }
        text.push_str("}\n\n");
        text.push_str(
            "export type StreamName = keyof Streams;\n\
             export type StreamSpecOf<S extends StreamName> = Streams[S][\"spec\"];\n\
             export type StreamItemOf<S extends StreamName> = Streams[S][\"item\"];\n\n\
             export interface StreamInfo {\n\
             \x20 readonly scope: T.Scope;\n\
             \x20 /** Which `StreamCursor` variant the stream resumes from. */\n\
             \x20 readonly cursor: \"none\" | \"sequence\" | \"revision\" | \"offset\";\n\
             \x20 /** Whether the stream also carries DATA frames under credit. */\n\
             \x20 readonly data: boolean;\n\
             }\n\n\
             export const STREAMS: { readonly [S in StreamName]: StreamInfo } = {\n",
        );
        for stream in &streams {
            let _ = writeln!(
                text,
                "  {}: {{ scope: {}, cursor: {}, data: {} }},",
                property_name(stream["name"].as_str().unwrap_or_default()),
                stream["scope"],
                stream["cursor"],
                stream["data"]
            );
        }
        text.push_str("};\n");
        text
    }

    /// A TypeScript expression normalizing `expression` of type `schema`, or
    /// `None` when nothing inside it can be an unknown tag.
    fn normalize_expression(&self, schema: &Value, expression: &str) -> Option<String> {
        let schema = without_null(schema);
        if let Some(name) = reference_name(&schema)
            && schema.get("properties").is_none()
        {
            return self
                .needs
                .contains(name)
                .then(|| format!("normalize{name}({expression})"));
        }
        if !schema_needs(&schema, &self.needs) {
            return None;
        }
        match schema.get("type").and_then(Value::as_str) {
            Some("array") => {
                let item = self.normalize_expression(schema.get("items")?, "item")?;
                Some(format!("{expression}.map((item: any) => {item})"))
            }
            Some("object") if schema.get("properties").is_none() => {
                let value =
                    self.normalize_expression(schema.get("additionalProperties")?, "item")?;
                Some(format!(
                    "normalizeMap({expression}, (item: any) => {value})"
                ))
            }
            _ => panic!("waku-codegen cannot normalize an inline union or object yet: {schema}"),
        }
    }

    /// Statements normalizing the properties of the object `value`.
    fn normalize_properties(&self, schema: &Value, indent: &str) -> String {
        let mut text = String::new();
        let Some(properties) = schema.get("properties").and_then(Value::as_object) else {
            return text;
        };
        for (name, property) in properties {
            if name == "type" {
                continue;
            }
            let access = format!("value[{}]", serde_json::to_string(name).unwrap());
            if let Some(expression) = self.normalize_expression(property, &access) {
                let _ = writeln!(
                    text,
                    "{indent}if ({access} != null) {access} = {expression};"
                );
            }
        }
        text
    }

    fn decode(&self, document: &Value) -> String {
        let mut text = format!(
            "{HEADER}\n\
             import type * as T from \"./types\";\n\
             import type {{ MethodName, MethodResultOf }} from \"./methods\";\n\
             import type {{ StreamItemOf, StreamName }} from \"./streams\";\n\n\
             // Decoded values are normalized in place: only the parts that can hold\n\
             // an open union are visited, and a tag this client does not know becomes\n\
             // `{{ type: \"unknown\", rawType }}`.\n\n\
             function normalizeMap(value: any, normalize: (item: any) => any): any {{\n\
             \x20 for (const key of Object.keys(value)) value[key] = normalize(value[key]);\n\
             \x20 return value;\n\
             }}\n"
        );
        for (name, schema) in &self.definitions {
            if !self.needs.contains(name) {
                continue;
            }
            let _ = write!(
                text,
                "\nexport function normalize{name}(value: any): T.{name} {{\n"
            );
            if let Some(variants) = schema.get("oneOf").and_then(Value::as_array) {
                text.push_str("  switch (value?.type) {\n");
                for variant in variants {
                    let Some(tag) = tag_of(variant) else { continue };
                    if is_unknown_tag(tag) {
                        continue;
                    }
                    let _ = writeln!(text, "    case {}: {{", serde_json::to_string(tag).unwrap());
                    text.push_str(&self.normalize_properties(variant, "      "));
                    match reference_name(variant).filter(|name| self.needs.contains(*name)) {
                        Some(inner) => {
                            let _ =
                                writeln!(text, "      return normalize{inner}(value) as T.{name};");
                        }
                        None => text.push_str("      return value;\n"),
                    }
                    text.push_str("    }\n");
                }
                text.push_str(
                    "    default:\n      return { type: \"unknown\", rawType: String(value?.type) } as T.",
                );
                let _ = writeln!(text, "{name};\n  }}\n}}");
                continue;
            }
            if schema.get("properties").is_some() {
                text.push_str(&self.normalize_properties(schema, "  "));
                text.push_str("  return value;\n}\n");
            } else {
                let expression = self
                    .normalize_expression(schema, "value")
                    .unwrap_or_else(|| "value".into());
                let _ = writeln!(text, "  return {expression};\n}}");
            }
        }
        text.push_str(
            "\n/** Normalizes a reply's `ok` by the method of its call. */\n\
             export const resultNormalizers: { readonly [M in MethodName]: (value: any) => MethodResultOf<M> } = {\n",
        );
        for method in document
            .get("methods")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
        {
            let expression = self
                .normalize_expression(&method["result"], "value")
                .unwrap_or_else(|| "value".into());
            let _ = writeln!(
                text,
                "  {}: (value: any) => {expression},",
                serde_json::to_string(method["name"].as_str().unwrap_or_default()).unwrap()
            );
        }
        text.push_str(
            "};\n\n/** Normalizes one item by the stream of its subscription. */\n\
             export const itemNormalizers: { readonly [S in StreamName]: (value: any) => StreamItemOf<S> } = {\n",
        );
        for stream in document
            .get("streams")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
        {
            let expression = self
                .normalize_expression(&stream["item"], "value")
                .unwrap_or_else(|| "value".into());
            let _ = writeln!(
                text,
                "  {}: (value: any) => {expression},",
                property_name(stream["name"].as_str().unwrap_or_default())
            );
        }
        text.push_str("};\n");
        text
    }
}

fn constants(document: &Value) -> String {
    let mut text = String::from(HEADER);
    text.push('\n');
    if let Some(constants) = document.get("constants").and_then(Value::as_object) {
        for (name, value) in constants {
            let _ = writeln!(text, "export const {name} = {value} as const;");
        }
    }
    let protocol = &document["protocol"];
    let _ = writeln!(
        text,
        "export const PREFACE = {} as const;",
        protocol["preface"]
    );
    let _ = writeln!(
        text,
        "export const WEBSOCKET_PATH = {} as const;",
        protocol["websocketPath"]
    );
    let _ = writeln!(
        text,
        "export const WEBSOCKET_SUBPROTOCOL = {} as const;",
        protocol["websocketSubprotocol"]
    );
    let _ = writeln!(
        text,
        "export const SCOPES = {} as const;",
        document["scopes"]
    );
    let _ = writeln!(
        text,
        "export const ERROR_CODES = {} as const;",
        document["errorCodes"]
    );
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn unions_optional_fields_and_open_enums() {
        let document = json!({
            "$defs": {
                "Item": { "oneOf": [
                    { "type": "object", "properties": {
                        "type": { "type": "string", "const": "snapshot" },
                        "note": { "type": ["string", "null"] },
                        "kind": { "$ref": "#/$defs/Kind" },
                    }, "required": ["type", "kind"] },
                    { "type": "object", "properties": { "type": { "type": "string", "const": "unknown" } }, "required": ["type"] },
                ] },
                "Kind": { "type": "string", "enum": ["a", "b"], "x-waku-open": true },
                "Holder": { "type": "object", "properties": {
                    "items": { "type": "array", "items": { "$ref": "#/$defs/Item" } },
                    "byName": { "type": "object", "additionalProperties": { "$ref": "#/$defs/Item" } },
                    "maybe": { "anyOf": [{ "$ref": "#/$defs/Item" }, { "type": "null" }] },
                }, "required": ["items", "byName"] },
            },
            "methods": [],
            "streams": [],
            "constants": {},
            "protocol": { "preface": [1], "websocketPath": "/v8", "websocketSubprotocol": "waku.v8" },
            "scopes": [],
            "errorCodes": [],
        });
        let files = generate(&document);
        let types = &files["types.ts"];
        assert!(
            types.contains("export type Kind = \"a\" | \"b\" | (string & {});"),
            "{types}"
        );
        assert!(
            types.contains("  type: \"snapshot\";\n  kind: Kind;\n  note?: string;"),
            "{types}"
        );
        assert!(
            types.contains("{ type: \"unknown\"; rawType: string }"),
            "{types}"
        );
        assert!(types.contains("maybe?: Item;"), "{types}");
        let decode = &files["decode.ts"];
        assert!(
            decode.contains("export function normalizeItem(value: any): T.Item {"),
            "{decode}"
        );
        assert!(decode.contains("if (value[\"items\"] != null) value[\"items\"] = value[\"items\"].map((item: any) => normalizeItem(item));"), "{decode}");
        assert!(
            decode.contains("normalizeMap(value[\"byName\"], (item: any) => normalizeItem(item))"),
            "{decode}"
        );
        assert!(
            decode.contains(
                "if (value[\"maybe\"] != null) value[\"maybe\"] = normalizeItem(value[\"maybe\"]);"
            ),
            "{decode}"
        );
        assert!(!decode.contains("normalizeKind"), "{decode}");
    }

    #[test]
    fn generation_is_deterministic() {
        let document = crate::schema_document();
        assert_eq!(generate(&document), generate(&document));
    }
}
